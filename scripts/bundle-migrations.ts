import { readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import journal from "../src/db/migrations/meta/_journal.json";

const directory = join(import.meta.dir, "../src/db/migrations");
const migrations: Record<string, string> = {};
for (const entry of journal.entries) {
  migrations[`m${String(entry.idx).padStart(4, "0")}`] = await readFile(
    join(directory, `${entry.tag}.sql`),
    "utf8",
  );
}
await rm(join(directory, "migrations.js"), { force: true });
await writeFile(
  join(directory, "bundle.ts"),
  `// Generated by bun run db:generate.\nexport default ${JSON.stringify({ journal, migrations }, null, 2)};\n`,
);
