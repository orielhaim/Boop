export type IconName = keyof typeof icons;

export function isIconName(name: string): name is IconName {
  return Object.hasOwn(icons, name);
}

export const iconNames = Object.keys(icons).filter(isIconName);
export type { IconWeight };

const mirroredInRtl = new Set<IconName>([
  "back",
  "previous",
  "next",
  "continue",
  "reply",
  "forward",
  "erase",
  "unarchive",
]);

const defaultWeights: Partial<Record<IconName, IconWeight>> = {
  favorite: "fill",
  pause: "fill",
  play: "fill",
};

export function Icon({
  name,
  size = 22,
  color,
  weight,
}: {
  name: IconName;
  size?: number;
  color?: string;
  weight?: IconWeight;
}) {
  const { colors } = useTheme();
  const { i18n } = useTranslation("common");
  const rtl = directionFor(resolveLanguage(i18n.resolvedLanguage)) === "rtl";
  const PhosphorIcon = icons[name];
  const iconWeight = weight ?? defaultWeights[name] ?? "regular";

  return (
    <View
      accessible={false}
      accessibilityElementsHidden
      importantForAccessibility="no-hide-descendants"
      style={{ width: size, height: size }}
    >
      <PhosphorIcon
        testID=""
        size={size}
        color={color ?? colors.accent}
        weight={iconWeight}
        mirrored={rtl && mirroredInRtl.has(name)}
      />
    </View>
  );
}
